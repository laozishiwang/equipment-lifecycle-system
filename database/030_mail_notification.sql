CREATE TABLE IF NOT EXISTS ems_mail_config (
  id TINYINT NOT NULL PRIMARY KEY,
  enabled TINYINT NOT NULL DEFAULT 0,
  host VARCHAR(255) NOT NULL DEFAULT '',
  port INT NOT NULL DEFAULT 465,
  security VARCHAR(16) NOT NULL DEFAULT 'SSL',
  username VARCHAR(255) NOT NULL DEFAULT '',
  password VARCHAR(512) NOT NULL DEFAULT '',
  sender VARCHAR(255) NOT NULL DEFAULT '',
  recipients TEXT NOT NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS ems_mail_outbox (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  order_id BIGINT NOT NULL,
  event_type VARCHAR(20) NOT NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
  attempts INT NOT NULL DEFAULT 0,
  available_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  lease_until DATETIME DEFAULT NULL,
  lease_owner VARCHAR(36) DEFAULT NULL,
  last_error VARCHAR(500) DEFAULT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  sent_at DATETIME DEFAULT NULL,
  UNIQUE KEY uk_mail_order_event (order_id,event_type),
  KEY idx_mail_pending (status,available_at,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
