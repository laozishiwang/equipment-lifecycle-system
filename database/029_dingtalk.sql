CREATE TABLE IF NOT EXISTS ems_dingtalk_config (
  id TINYINT NOT NULL PRIMARY KEY,
  enabled TINYINT NOT NULL DEFAULT 0,
  webhook VARCHAR(1024) NOT NULL DEFAULT '',
  secret VARCHAR(255) NOT NULL DEFAULT '',
  keyword VARCHAR(100) NOT NULL DEFAULT '',
  template VARCHAR(20) NOT NULL DEFAULT 'basic',
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS ems_dingtalk_outbox (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  order_id BIGINT NOT NULL,
  event_type VARCHAR(20) NOT NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
  attempts INT NOT NULL DEFAULT 0,
  available_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  lease_until DATETIME DEFAULT NULL,
  lease_owner VARCHAR(36) DEFAULT NULL,
  last_error VARCHAR(500) DEFAULT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  sent_at DATETIME DEFAULT NULL,
  UNIQUE KEY uk_dingtalk_order_event (order_id,event_type),
  KEY idx_dingtalk_pending (status,available_at,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
